struct ClipboardImage: Equatable {
    let data: Data
    let type: String
    let thumbnail: Data
    let width: Int
    let height: Int
    init?(data: Data, type: String) {
        guard data.count <= 10*1024*1024,
              let source = CGImageSourceCreateWithData(data as CFData,nil),
              let properties = CGImageSourceCopyPropertiesAtIndex(source,0,nil) as? [CFString:Any],
              let width = properties[kCGImagePropertyPixelWidth] as? Int,
              let height = properties[kCGImagePropertyPixelHeight] as? Int,
              width > 0,height > 0,width <= 16384,height <= 16384,width*height <= 16_000_000,
              let thumb = CGImageSourceCreateThumbnailAtIndex(source,0,[
                kCGImageSourceCreateThumbnailFromImageAlways:true,
                kCGImageSourceCreateThumbnailWithTransform:true,
                kCGImageSourceThumbnailMaxPixelSize:160,
                kCGImageSourceShouldCacheImmediately:true] as CFDictionary),
              let png = NSBitmapImageRep(cgImage:thumb).representation(using:.png,properties:[:]) else { return nil }
        self.data = data; self.type = type; self.thumbnail = png; self.width = width; self.height = height
    }
}
enum ClipboardEntry: Equatable {
    case text(String)
    case image(ClipboardImage)
    var summary: String {
        switch self {
        case .text(let text): return text
        case .image(let image): return "画像・スクショ  \(image.width) × \(image.height)"
        }
    }
    var bytes: Int {
        switch self { case .text(let text): return text.utf8.count; case .image(let image): return image.data.count+image.thumbnail.count }
    }
}
struct ClipboardHistory {
    private(set) var entries: [ClipboardEntry] = []
    static let ignored: Set<String> = ["org.nspasteboard.ConcealedType","org.nspasteboard.TransientType","org.nspasteboard.AutoGeneratedType","com.agilebits.onepassword","net.antelle.keeweb"]
    private mutating func insert(_ entry: ClipboardEntry) {
        entries.removeAll { $0 == entry }; entries.insert(entry,at:0)
        while entries.count > 50 || entries.reduce(0, { $0+$1.bytes }) > 32*1024*1024 { entries.removeLast() }
    }
    mutating func record(_ text: String?, types: Set<String>, secure: Bool) {
        guard !secure, types.isDisjoint(with:Self.ignored), let text = text, !text.isEmpty, text.utf16.count <= 16384 else { return }
        insert(.text(text))
    }
    mutating func recordImage(_ data: Data, type: String, types: Set<String>, secure: Bool) {
        guard !secure,types.isDisjoint(with:Self.ignored),
              [NSPasteboard.PasteboardType.png.rawValue,NSPasteboard.PasteboardType.tiff.rawValue].contains(type),
              let image = ClipboardImage(data:data,type:type) else { return }
        insert(.image(image))
    }
    mutating func clear() { entries.removeAll() }
}

final class ClipboardHistoryController: NSObject, NSTableViewDataSource, NSTableViewDelegate, NSSearchFieldDelegate {
    private var history = ClipboardHistory()
    private var timer: Timer?
    private let board: NSPasteboard
    private var observed = -1
    private var enabled = false
    private var previousApp: NSRunningApplication?
    private var rows: [ClipboardEntry] = []
    let panel = NSPanel(contentRect:NSRect(x:0,y:0,width:570,height:450),styleMask:[.titled,.closable,.resizable],backing:.buffered,defer:false)
    private let toggle = StudioToggle(title:"文字・画像の履歴を記録する",target:nil,action:nil)
    private let search = NSSearchField()
    private let table = NSTableView()
    private let copyButton = NSButton(title:"選択した項目をコピー",target:nil,action:nil)
    private let note = NSTextField(wrappingLabelWithString:"")
    var onEnabledChanged: ((Bool) -> Bool)?
    init(board: NSPasteboard = .general) {
        self.board = board; super.init()
        panel.title = "クリップボード履歴"; panel.isReleasedWhenClosed = false; panel.minSize = NSSize(width:480,height:360)
        let body = NSView(); panel.contentView = body
        toggle.target = self; toggle.action = #selector(changeEnabled)
        search.placeholderString = "履歴を検索"; search.delegate = self
        let column = NSTableColumn(identifier:NSUserInterfaceItemIdentifier("text")); column.title = "コピーした文字・画像"; column.width = 510; table.addTableColumn(column)
        table.delegate = self; table.dataSource = self; table.rowHeight = 56; table.target = self; table.doubleAction = #selector(copySelected)
        let scroll = NSScrollView(); scroll.documentView = table; scroll.hasVerticalScroller = true
        copyButton.target = self; copyButton.action = #selector(copySelected)
        let clear = NSButton(title:"履歴を全消去",target:self,action:#selector(clearHistory))
        let buttons = NSStackView(views:[copyButton,clear]); buttons.orientation = .horizontal; buttons.spacing = 12
        let stack = NSStackView(views:[toggle,search,scroll,buttons,note]); stack.orientation = .vertical; stack.alignment = .leading; stack.spacing = 12; stack.translatesAutoresizingMaskIntoConstraints = false; body.addSubview(stack)
        NSLayoutConstraint.activate([stack.topAnchor.constraint(equalTo:body.topAnchor,constant:18),stack.bottomAnchor.constraint(equalTo:body.bottomAnchor,constant:-18),stack.leadingAnchor.constraint(equalTo:body.leadingAnchor,constant:18),stack.trailingAnchor.constraint(equalTo:body.trailingAnchor,constant:-18),scroll.heightAnchor.constraint(greaterThanOrEqualToConstant:140)])
        for item in [search,scroll,note] as [NSView] { item.widthAnchor.constraint(equalTo:stack.widthAnchor).isActive = true }
        refresh()
    }
    func setEnabled(_ value: Bool) {
        guard value != enabled else { return }
        enabled = value; toggle.state = value ? .on : .off
        timer?.invalidate(); timer = nil; observed = board.changeCount
        if value {
            let timer = Timer(timeInterval:0.5,repeats:true) { [weak self] _ in self?.poll() }
            self.timer = timer; RunLoop.main.add(timer,forMode:.common)
        } else { history.clear() }
        refresh()
    }
    private func poll() {
        guard enabled, board.changeCount != observed else { return }
        observed = board.changeCount
        let types = Set((board.types ?? []).map { $0.rawValue })
        guard !IsSecureEventInputEnabled(), types.isDisjoint(with:ClipboardHistory.ignored) else { return }
        if let type = [NSPasteboard.PasteboardType.png,.tiff].first(where:{ board.types?.contains($0) == true }),
           let data = board.data(forType:type) {
            history.recordImage(data,type:type.rawValue,types:types,secure:false)
        } else { history.record(board.string(forType:.string),types:types,secure:false) }
        refresh()
    }
    func show() {
        if let app = NSWorkspace.shared.frontmostApplication, app.processIdentifier != ProcessInfo.processInfo.processIdentifier { previousApp = app }
        refresh(); panel.center(); panel.makeKeyAndOrderFront(nil); NSApp.activate(ignoringOtherApps:true); panel.makeFirstResponder(search)
    }
    @objc private func changeEnabled() {
        let desired = toggle.state == .on
        if onEnabledChanged?(desired) == true { setEnabled(desired) }
        else { toggle.state = enabled ? .on : .off }
    }
    @objc private func clearHistory() { history.clear(); refresh() }
    @objc private func copySelected() {
        guard rows.indices.contains(table.selectedRow) else { return }
        let value = rows[table.selectedRow]
        board.clearContents()
        let copied: Bool
        switch value {
        case .text(let text): copied = board.setString(text,forType:.string)
        case .image(let image): copied = board.setData(image.data,forType:NSPasteboard.PasteboardType(image.type))
        }
        guard copied else { note.stringValue = "コピーできませんでした。"; return }
        observed = board.changeCount; panel.orderOut(nil); previousApp?.activate(options:[])
    }
    func controlTextDidChange(_ notification: Notification) { refresh() }
    func tableViewSelectionDidChange(_ notification: Notification) { copyButton.isEnabled = rows.indices.contains(table.selectedRow) }
    private func refresh() {
        let selected = rows.indices.contains(table.selectedRow) ? rows[table.selectedRow] : nil
        let query = search.stringValue
        rows = history.entries.filter { query.isEmpty || $0.summary.localizedCaseInsensitiveContains(query) }
        table.reloadData()
        if let selected = selected, let index = rows.firstIndex(of:selected) { table.selectRowIndexes(IndexSet(integer:index),byExtendingSelection:false) }
        else { table.deselectAll(nil) }
        copyButton.isEnabled = rows.indices.contains(table.selectedRow)
        note.stringValue = enabled ? "\(rows.count)件 · ダブルクリックで再コピー。貼り付け先で⌘Vを押してください。最大50件・合計32MB、画像は1件10MB／1600万画素まで。終了時に消去。機密指定のあるコピーは記録しません。" : "記録はOFFです。ONにした後の文字・画像を記録します。履歴はディスクに保存しません。"
    }
    func numberOfRows(in tableView: NSTableView) -> Int { rows.count }
    func tableView(_ tableView: NSTableView, viewFor tableColumn: NSTableColumn?, row: Int) -> NSView? {
        let entry = rows[row]
        let field = NSTextField(labelWithString:entry.summary.replacingOccurrences(of:"\n",with:" ⏎ "))
        field.lineBreakMode = .byTruncatingTail
        if case .image(let image) = entry {
            let thumbnail = NSImageView(); thumbnail.image = NSImage(data:image.thumbnail); thumbnail.imageScaling = .scaleProportionallyUpOrDown
            thumbnail.widthAnchor.constraint(equalToConstant:72).isActive = true
            thumbnail.heightAnchor.constraint(equalToConstant:48).isActive = true
            let stack = NSStackView(views:[thumbnail,field]); stack.spacing = 12
            stack.setAccessibilityLabel(entry.summary); return stack
        }
        return field
    }
    static func verify() {
        var model = ClipboardHistory()
        model.record("first",types:[],secure:false); model.record("second",types:[],secure:false); model.record("first",types:[],secure:false)
        verifySmoke(model.entries == [.text("first"),.text("second")])
        model.record("secret",types:["org.nspasteboard.ConcealedType"],secure:false)
        model.record("secure",types:[],secure:true); verifySmoke(model.entries.count == 2)
        for i in 0..<60 { model.record(String(i),types:[],secure:false) }
        verifySmoke(model.entries.count == 50 && model.entries.first == .text("59"))
        model.clear(); verifySmoke(model.entries.isEmpty)
        let board = NSPasteboard.withUniqueName(); defer { board.releaseGlobally() }
        let controller = ClipboardHistoryController(board:board)
        controller.setEnabled(true); board.setString("isolated",forType:.string); controller.observed = board.changeCount-1
        // Model/UI validation uses an isolated pasteboard, never the user's clipboard.
        controller.history.record("isolated",types:[],secure:false); controller.refresh()
        verifySmoke(controller.rows == [.text("isolated")])
        controller.table.selectRowIndexes(IndexSet(integer:0),byExtendingSelection:false)
        controller.history.record("newest",types:[],secure:false); controller.refresh()
        verifySmoke(controller.table.selectedRow == 1,"New history must not replace the user's selection")
        controller.panel.contentView!.layoutSubtreeIfNeeded()
        saveSmokePreview(controller.panel.contentView!,to:URL(fileURLWithPath:CommandLine.arguments[2]).deletingPathExtension().path + "-clipboard.png")
        let bitmap = NSBitmapImageRep(bitmapDataPlanes:nil,pixelsWide:8,pixelsHigh:6,bitsPerSample:8,samplesPerPixel:4,hasAlpha:true,isPlanar:false,colorSpaceName:.deviceRGB,bytesPerRow:0,bitsPerPixel:0)!
        memset(bitmap.bitmapData!,255,bitmap.bytesPerRow*bitmap.pixelsHigh)
        let png = bitmap.representation(using:.png,properties:[:])!
        controller.history.recordImage(png,type:NSPasteboard.PasteboardType.png.rawValue,types:[],secure:false)
        controller.refresh(); verifySmoke(controller.rows.first?.summary == "画像・スクショ  8 × 6")
        controller.panel.contentView!.layoutSubtreeIfNeeded()
        saveSmokePreview(controller.panel.contentView!,to:URL(fileURLWithPath:CommandLine.arguments[2]).deletingPathExtension().path + "-clipboard-image.png")
        let count = controller.history.entries.count
        controller.history.recordImage(png,type:NSPasteboard.PasteboardType.png.rawValue,types:[],secure:false)
        verifySmoke(controller.history.entries.count == count,"Image deduplication")
        controller.history.recordImage(png,type:NSPasteboard.PasteboardType.png.rawValue,types:["org.nspasteboard.ConcealedType"],secure:false)
        controller.history.recordImage(Data([1,2,3]),type:NSPasteboard.PasteboardType.png.rawValue,types:[],secure:false)
        verifySmoke(controller.history.entries.count == count,"Private/invalid images excluded")
        controller.table.selectRowIndexes(IndexSet(integer:0),byExtendingSelection:false)
        controller.copySelected(); verifySmoke(board.data(forType:.png) == png,"Image recopy retains original bytes and type")
        controller.search.stringValue = "画像"; controller.refresh(); verifySmoke(controller.rows.count == 1,"Image search")
        controller.search.stringValue = "absent"; controller.refresh(); verifySmoke(controller.rows.isEmpty)
        controller.setEnabled(false); verifySmoke(controller.history.entries.isEmpty && controller.timer == nil)
        print("PASS: clipboard text/image deduplication, bounded images, original image recopy, confidential/secure exclusion, search and OFF cleanup; general clipboard untouched")
    }
}
